#Arithmetic operator
a =5
b =3
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a//b)
print(a%b)
print(a**b)

#comparison operator
print(a<b)
print(a>b)
print(a==b)
print(a!=b)
print(a<=b)
print(a>=b)

#logical operator
x =True 
y =False
print(x or y)
print(x and y)
print(not y)

# bitwise operator
x =2
y =3
print(x & y)
print(x | y)
print(x>>3)
print(y<<2)
print(~x)

# assignment operator
a =2
a+=3
a-=3
a*=3
a/=9
a+=1
a-=3

#identity operator
a =3
b =3
print(a is b)

a ="hello"
b ="hello"
print(a is b)

a =[2,3,4]
b =[2,3,4]
print(a is b)

#membership operator
m ="delhi"
print('e' in m)
print('s' not in m)


